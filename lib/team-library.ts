export const teamGroup = (key: string) => TEAM_LIBRARY.find((g) => g.key === key);
export const libraryRole = (key: string) => TEAM_LIBRARY.flatMap((g) => g.roles).find((r) => r.key === key);
export const libraryDepartment = (key: string) => TEAM_LIBRARY.flatMap((g) => g.departments).find((d) => d.key === key);

/**
 * The library groups suggested to a client: its own kind first, then what every business has. `choice` is what Type of
 * business shows (kindChoice in lib/business-types.ts): a kind such as "dental", or a type such as "retail" or "custom".
 */
export function suggestedGroups(choice: string): TeamLibraryGroup[] {
  const own = choice === "general" ? undefined : teamGroup(choice);
  return [own, teamGroup("general")].filter((g): g is TeamLibraryGroup => Boolean(g));
}

// NFKD splits أ إ آ into ا plus a mark, so dropping the marks also folds them to ا
const norm = (s: string) => s.toLowerCase().normalize("NFKD").replace(/[\u064B-\u065F\u0670]/g, "").replace(/\u0629/g, "\u0647").replace(/\u0649/g, "\u064A").trim();

/** Library roles whose English or Arabic names contain `q`, each name once (the first group it appears in wins). */
export function searchRoles(q: string, groupKey?: string): (LibraryRole & { group: string })[] {
  const n = norm(q);
  const seen = new Set<string>();
  const out: (LibraryRole & { group: string })[] = [];
  for (const g of TEAM_LIBRARY) {
    if (groupKey && g.key !== groupKey) continue;
    for (const r of g.roles) {
      if (n && !norm(`${r.one} ${r.many} ${r.oneAr} ${r.manyAr}`).includes(n)) continue;
      const id = r.one.toLowerCase();
      if (seen.has(id)) continue;
      seen.add(id);
      out.push({ ...r, group: g.key });
    }
  }
  return out;
}

/** Library departments whose English or Arabic names contain `q`, each name once. */
export function searchDepartments(q: string, groupKey?: string): (LibraryDepartment & { group: string })[] {
  const n = norm(q);
  const seen = new Set<string>();
  const out: (LibraryDepartment & { group: string })[] = [];
  for (const g of TEAM_LIBRARY) {
    if (groupKey && g.key !== groupKey) continue;
    for (const d of g.departments) {
      if (n && !norm(`${d.en} ${d.ar}`).includes(n)) continue;
      const id = d.en.toLowerCase();
      if (seen.has(id)) continue;
      seen.add(id);
      out.push({ ...d, group: g.key });
    }
  }
  return out;
}

/** The library role with this English or Arabic name (any form), to fill the other language when a person types only one. */
export function findRoleByName(name: string): LibraryRole | undefined {
  const n = norm(name);
  if (!n) return undefined;
  return TEAM_LIBRARY.flatMap((g) => g.roles).find((r) => [r.one, r.many, r.oneAr, r.manyAr].some((x) => norm(x) === n));
}

/** The library department with this English or Arabic name. */
export function findDepartmentByName(name: string): LibraryDepartment | undefined {
  const n = norm(name);
  if (!n) return undefined;
  return TEAM_LIBRARY.flatMap((g) => g.departments).find((d) => norm(d.en) === n || norm(d.ar) === n);
}
