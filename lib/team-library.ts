/**
 * The roles and departments library (2026-11-02): for each of the 20 kinds of business (lib/service-library.ts keys), plus
 * shops and roles every business has, the usual job titles (singular and plural, English and Arabic) and the usual
 * departments. A client picks from it on Business > Roles and departments; the names are only a start and can be changed.
 * Pure data, shared by server and browser.
 */

export interface LibraryRole { key: string; one: string; many: string; oneAr: string; manyAr: string }
export interface LibraryDepartment { key: string; en: string; ar: string }
export interface TeamLibraryGroup { key: string; roles: LibraryRole[]; departments: LibraryDepartment[] }

type R = [one: string, many: string, oneAr: string, manyAr: string];
type D = [en: string, ar: string];

const slug = (s: string) => s.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const group = (key: string, roles: R[], departments: D[]): TeamLibraryGroup => ({
  key,
  roles: roles.map(([one, many, oneAr, manyAr]) => ({ key: `${key}.${slug(one)}`, one, many, oneAr, manyAr })),
  departments: departments.map(([en, ar]) => ({ key: `${key}.${slug(en)}`, en, ar })),
});

